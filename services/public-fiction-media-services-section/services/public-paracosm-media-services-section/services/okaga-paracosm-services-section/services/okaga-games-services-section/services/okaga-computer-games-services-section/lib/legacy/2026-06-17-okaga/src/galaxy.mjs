// galaxy — okaga's navigable star map, read straight off the tsander engine's federated WORLD trace.
// A star SYSTEM is a subject `e`; the facts you know about it are the rows filed under `e`; the system
// you EXPERIENCE is the per-observer fold of every trace that reaches `e` (tsander/world `place`). This
// module adds only okaga's navigation reading on top of that engine substrate:
//
//   - DISCOVERY by visiting. A system is on the map only once it has been SETTLED — i.e. it has any
//     evidence (`place().visited`). A never-visited subject is ⊥ FOG: you can see a dim flicker where a
//     lane leads, but you cannot trade there or read its prices until you GO. Exploration creates the
//     map (the design note's "the system is generated by whoever has been there").
//   - JUMP-LANES are relational edges. A row `(sys-a, lane, sys-b)` is a flyable jump from a→b. The
//     reachable frontier from where you are is the set of lane-objects out of your current system.
//   - CHOKEPOINTS from the cost-graph. okaga reads @561-group/computer/distribution/cost over the lane
//     graph: a CUT-VERTEX system is a natural monopoly (its removal splits the galaxy), a BRIDGE-EDGE
//     lane is a chokepoint a pirate can blockade. The economy IS the graph topology (design note §8).
//   - CONTESTED ⊤ stars. A system two traces DISAGREE about folds to ⊤ — held, both witnesses kept —
//     and is a Schrödinger star: it shows up TWICE on the wireframe (tsander's doubled+shivering
//     render) and is owned by BOTH factions. okaga surfaces these as `contestedSystems` so a player can
//     find them, dock at one face, or void-trade the disagreement without resolving it.
//
// THE LAW kept here: state is the append-only trace (we only READ it; jumps APPEND, never overwrite);
// ⊤ is HELD (a contested star is content, never collapsed for us); evidence is linear (a jump spends a
// fuel row and cannot be free-duplicated — enforced in game.mjs). Pure over the engine world.

import {
  place, positionOf, renderables, disagreements,
  subjects, logFor, relateFrom, allRows, admitLog, predicate,
} from "@561-group/tsander/world";
import { costGraphSummary } from "@561-group/computer/distribution/cost";

// the relation an okaga jump-lane row uses. A row `(a, LANE, b)` means "you can jump from a to b".
export const LANE = "lane";

// OKAGA_OPTS — the fold options every okaga read threads, so the engine sees okaga's full converse map.
// The engine's default converse (world.CONVERSE) knows `not-controlled-by` etc.; okaga ADDS its own
// negative faces — `not-autopilot` (a ship whose flight computer settled ⊤ charges both faces of its
// `autopilot` cell, and we want that to FOLD to ⊤ so the ship renders DOUBLED). Without this, the two
// faces never meet and a contested ship reads merely `t`. Pass this to every place/renderables read so
// the bilattice readout is consistent across the cockpit. (Functional set stays the engine default —
// `at-position` is single-valued; `controlled-by`/`autopilot` are NOT, a contested unit holds both.)
export const OKAGA_OPTS = Object.freeze({
  converse: { "not-autopilot": "autopilot" },
});

// withOkaga(opts) — merge a caller's fold opts over OKAGA_OPTS so okaga's converse map is always present
// (the caller can still add/override). Every charge-folding read below routes through this.
export function withOkaga(opts = {}) {
  return { ...OKAGA_OPTS, ...opts, converse: { ...OKAGA_OPTS.converse, ...(opts.converse ?? {}) } };
}

// systemsKnown(world) — every subject that has been VISITED (has any evidence). These are the systems
// on your map. A subject with NO rows is ⊥ fog and not listed here (you have to go to settle it).
export function systemsKnown(world, opts = {}) {
  const o = withOkaga(opts);
  const out = [];
  for (const subject of subjects(world)) {
    const p = place(world, subject, o);
    if (p.visited) out.push(subject);
  }
  return out.sort((a, b) => a.localeCompare(b));
}

// lanesFrom(world, system) — the jump-lanes OUT of `system`: the objects of its `lane` rows. Each lane
// target may itself be ⊥ (a lane into fog — you see it leads somewhere, but not what is there). Returns
// `{ to, known }` so the UI can draw settled destinations solid and fog destinations dim.
export function lanesFrom(world, system, opts = {}) {
  const o = withOkaga(opts);
  const targets = relateFrom(logFor(world, system), system, LANE);
  const seen = new Set();
  const out = [];
  for (const to of targets) {
    if (typeof to !== "string" || seen.has(to)) continue;
    seen.add(to);
    out.push({ to, known: place(world, to, o).visited });
  }
  return out.sort((a, b) => a.to.localeCompare(b.to));
}

// reachable(world, system) — just the lane-target ids out of `system` (the legal next jumps).
export function reachable(world, system, opts = {}) {
  return lanesFrom(world, system, opts).map((l) => l.to);
}

// canJump(world, from, to) — is there a lane from `from` to `to`? (Append-only legality of a jump; the
// fuel cost is game.mjs's concern.)
export function canJump(world, from, to, opts = {}) {
  return reachable(world, from, opts).includes(to);
}

// systemState(world, system) — okaga's full reading of one system: its charge, whether it is contested
// (⊤), who controls it (possibly BOTH — held), its station, hazards, position, and its lanes. This is
// what the cockpit shows when you settle the system you are in (design note §4 step 1).
export function systemState(world, system, opts = {}) {
  const o = withOkaga(opts);
  const p = place(world, system, o);
  const log = logFor(world, system);
  const controllers = uniq(relateFrom(log, system, "controlled-by"));
  const stations = uniq(relateFrom(log, system, "has-station"));
  const hazards = uniq(relateFrom(log, system, "hazard"));
  return {
    system,
    visited: p.visited,
    charge: p.charge,            // t settled · ⊥ fog · ⊤ contested · f denied
    contested: p.charge === "top",
    controllers,                 // a contested star has MORE THAN ONE — both held
    stations,
    hazards,
    position: positionOf(world, system, o),
    lanes: lanesFrom(world, system, o),
    contestedCells: p.contested, // the ⊤ cells, both witnesses kept (void-trade fodder)
  };
}

// contestedSystems(world) — every Schrödinger star in the galaxy: a subject with at least one ⊤ cell.
// These are the doubled+shivering stars on the wireframe; each entry carries the contested predicate and
// BOTH witnesses, so a void-trader can broker the disagreement without collapsing it.
export function contestedSystems(world, opts = {}) {
  const bySubject = new Map();
  for (const d of disagreements(world, withOkaga(opts))) {
    if (!bySubject.has(d.subject)) bySubject.set(d.subject, []);
    bySubject.get(d.subject).push({ predicate: d.predicate, witnesses: d.evidence ?? d.witnesses });
  }
  return [...bySubject.entries()]
    .map(([system, cells]) => ({ system, cells }))
    .sort((a, b) => a.system.localeCompare(b.system));
}

// chokepoints(world) — the cost-graph bottlenecks of the LANE network: cut-vertex systems (monopolies)
// and bridge-edge lanes (blockade points). okaga restricts the cost read to `lane` rows so the topology
// is the FLYABLE galaxy, not every incidental relation (a station name, a controller). Returns the
// cost.mjs summary plus the two lists named for okaga's economy.
export function chokepoints(world) {
  const laneRows = allRows(world).filter((r) => r.a === LANE && typeof r.v === "string");
  const summary = costGraphSummary(laneRows);
  return {
    monopolies: summary.graph.cutVertices.map((v) => v.id),       // cut-vertex systems
    blockades: summary.graph.bridgeEdges.map((e) => ({ from: e.from, to: e.to })), // bridge-edge lanes
    summary,
  };
}

// mapView(world, current) — a compact whole-galaxy readout for the cockpit's nav panel: every known
// system with its charge and whether it is the current one or directly reachable. ⊥ lane targets are
// folded in as fog entries so the player sees "there is something out there" without it being settled.
export function mapView(world, current, opts = {}) {
  const known = new Set(systemsKnown(world, opts));
  const rows = [];
  for (const system of known) {
    const st = systemState(world, system, opts);
    rows.push({
      system,
      charge: st.charge,
      current: system === current,
      reachable: current ? canJump(world, current, system, opts) : false,
      controllers: st.controllers,
    });
  }
  // fog: lane targets out of `current` that are NOT yet known — dim, unsettled, "go to discover".
  if (current) {
    for (const l of lanesFrom(world, current, opts)) {
      if (!known.has(l.to)) {
        rows.push({ system: l.to, charge: "bot", current: false, reachable: true, controllers: [], fog: true });
      }
    }
  }
  return rows.sort((a, b) => a.system.localeCompare(b.system));
}

// ── helpers ──
function uniq(xs) {
  return [...new Set(xs.filter((x) => typeof x === "string"))].sort((a, b) => a.localeCompare(b));
}

// re-export the engine reads okaga callers most want, so a consumer imports one module.
export { place, positionOf, renderables, admitLog, predicate, allRows, logFor, relateFrom };
