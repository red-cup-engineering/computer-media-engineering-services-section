import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {projectAgentEpisodeReading} from '../src/agent-episode-reading.mjs';

const fixtureUrl=new URL('./fixtures/services/public-paracosm-media-services-section/services/unassigned-floor-paracosm-services-section/content/production/episode-001.json',import.meta.url);
const load=async()=>JSON.parse(await readFile(fixtureUrl,'utf8'));
test('existing contested first episode is available as readable causal scenes without ratifying the art',async()=>{
 const reading=projectAgentEpisodeReading(await load());
 assert.equal(reading.type,'AgentEpisodeReading');
 assert.equal(reading.status,'PROVISIONAL_ARTISTIC_DEVELOPMENT');
 assert.equal(reading.media.durationMs,48000);
 assert.equal(reading.media.totalFrames,1440);
 assert.equal(reading.page.length,8);
 assert.equal(reading.page[0].id,'corridor-sweep');
 assert.equal(reading.page.at(-1).id,'other-latch');
 assert.equal(reading.causalBeats.length,4);
 assert.equal(reading.causalBeats.at(-1).causeBeatId,'hold-open');
 assert.equal(reading.causalBeats.at(-1).kind,'cliffhanger');
 assert.deepEqual(reading.declaredContradictions,[]);
 assert.equal(reading.source.canonDigestClaim,null);
});
test('a machine reader can page scenes and focus on witnessed appearances without inventing a speaker thought',async()=>{
 const source=await load();
 const page=projectAgentEpisodeReading(source,{limit:2});
 assert.equal(page.traversal.hasMore,true);
 assert.equal(page.traversal.nextAfter,'sift-map');
 const next=projectAgentEpisodeReading(source,{after:page.traversal.nextAfter,limit:2});
 assert.deepEqual(next.page.map(s=>s.id),['else-answers','route-dispute']);
 const elseOnly=projectAgentEpisodeReading(source,{focus:'else'});
 assert.deepEqual(elseOnly.page.map(s=>s.id),['else-answers','interval-refusal','cross-read']);
 assert.equal(elseOnly.viewpointSemantics.includes('never fabricates'),true);
 const last=projectAgentEpisodeReading(source,{focus:'else',after:'interval-refusal',limit:1});
 assert.deepEqual(last.page.map(s=>s.id),['cross-read']);
 assert.equal(last.traversal.hasMore,false);
 const fork=projectAgentEpisodeReading(source,{beat:'second-exit'});
 assert.deepEqual(fork.page.map(s=>s.id),['cross-read','other-latch']);
});
test('unread future turns do not leak through cast enumeration or global causal summaries',async()=>{
 const src=await load();
 const opening=projectAgentEpisodeReading(src,{limit:1});
 assert.deepEqual(opening.availableFocusCharacters,['latch']);
 assert.equal(opening.causalBeats.length,0,'first shot has not yet completed the vacancy beat');
 assert.equal(JSON.stringify(opening).includes('I voted to close it'),false);
 assert.equal(JSON.stringify(opening).includes('What standing do two contrary Latches'),false);
 const two=projectAgentEpisodeReading(src,{limit:2});
 assert.deepEqual(two.availableFocusCharacters,['latch','sift']);
 assert.deepEqual(two.causalBeats.map(b=>b.id),['vacancy']);
 assert.equal(two.availableFocusCharacters.includes('other-latch'),false);
 const middle=projectAgentEpisodeReading(src,{after:'sift-map',limit:2});
 assert.deepEqual(middle.causalBeats.map(b=>b.id),['vacancy','contested-map']);
 assert.equal(middle.availableFocusCharacters.includes('else'),true);
 assert.equal(middle.availableFocusCharacters.includes('other-latch'),false);
 const final=projectAgentEpisodeReading(src,{after:'cross-read',limit:1});
 assert.equal(final.page[0].id,'other-latch');
 assert.deepEqual(final.causalBeats.map(b=>b.id),['vacancy','contested-map','hold-open','second-exit']);
 assert.equal(final.availableFocusCharacters.includes('other-latch'),true);
});
test('broken causal edges, time bounds, cast identity, and selectors are rejected',async()=>{
 const source=await load();
 assert.throws(()=>projectAgentEpisodeReading(source,{focus:'ghost'}),/unknown on-screen focus/);
 assert.throws(()=>projectAgentEpisodeReading(source,{after:'invented-shot'}),/unknown shot cursor/);
 assert.throws(()=>projectAgentEpisodeReading(source,{limit:1000}),/bounded integer/);
 assert.throws(()=>projectAgentEpisodeReading(source,{beat:'unknown'}),/unknown causal beat/);
 const badCause=structuredClone(source);
 badCause.episode.beats[1].causeBeatId='future-beat';
 assert.throws(()=>projectAgentEpisodeReading(badCause),/forward cause/);
 const badAudio=structuredClone(source);
 badAudio.episode.shots[0].dialogue[0].endFrame=999;
 assert.throws(()=>projectAgentEpisodeReading(badAudio),/bounded integer/);
 const badIdentity=structuredClone(source);
 badIdentity.episode.shots[1].dialogue[0].speakerId='absent';
 assert.throws(()=>projectAgentEpisodeReading(badIdentity),/not present/);
});
test('declared source digest is not mistaken for an independent receiver attestation',async()=>{
 const source=await load();
 source.source.paracosm.canonDigest='ni:///sha-256;'+('A'.repeat(43));
 const reading=projectAgentEpisodeReading(source);
 assert.equal(reading.status,'PROVISIONAL_ARTISTIC_DEVELOPMENT');
 assert.match(reading.boundaries,/Not a ratified canon/);
});
test('read-only CLI streams actual pilot as bounded JSON with no provider side effects',async()=>{
 const cmd=fileURLToPath(new URL('../apps/read-agent-episode.mjs',import.meta.url));
 const path=fileURLToPath(fixtureUrl);
 const result=spawnSync(process.execPath,[cmd,path,'--focus','else','--limit','2'],{encoding:'utf8'});
 assert.equal(result.status,0,result.stderr);
 const out=JSON.parse(result.stdout);
 assert.equal(out.page.length,2);
 assert.equal(out.page[0].id,'else-answers');
 assert.equal(out.traversal.nextAfter,'interval-refusal');
 const invalid=spawnSync(process.execPath,[cmd,path,'--after','not-a-scene'],{encoding:'utf8'});
 assert.notEqual(invalid.status,0);
 assert.match(invalid.stderr,/unknown shot cursor/);
});
